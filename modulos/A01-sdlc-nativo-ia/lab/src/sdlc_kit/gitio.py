"""Thin, testable wrappers around ``git`` for the two places a check runs:
the staged index (pre-commit) and a commit range (CI)."""

from __future__ import annotations

import subprocess
from dataclasses import replace
from pathlib import Path

from sdlc_kit.findings import Finding
from sdlc_kit.policy import (
    ChangedFile,
    Policy,
    check_protected_paths,
    check_test_edits,
    scan_diff,
)


def _git(repo: Path, *args: str) -> str:
    proc = subprocess.run(
        ["git", "-C", str(repo), *args],
        capture_output=True,
        text=True,
        check=False,
    )
    if proc.returncode != 0:
        raise RuntimeError(f"git {' '.join(args)} failed: {proc.stderr.strip()}")
    return proc.stdout


def parse_name_status(output: str) -> list[ChangedFile]:
    """Parse ``--name-status``. A rename becomes delete(old) + add(new)."""
    files: list[ChangedFile] = []
    for line in output.splitlines():
        if not line.strip():
            continue
        parts = line.split("\t")
        status = parts[0][0]
        if status in {"R", "C"} and len(parts) == 3:
            if status == "R":
                files.append(ChangedFile("D", parts[1]))
            files.append(ChangedFile("A", parts[2]))
        else:
            files.append(ChangedFile(status, parts[-1]))
    return files


def current_branch(repo: Path) -> str:
    return _git(repo, "rev-parse", "--abbrev-ref", "HEAD").strip()


def staged(repo: Path) -> tuple[list[ChangedFile], str]:
    names = _git(repo, "diff", "--cached", "--name-status", "-M")
    diff = _git(repo, "diff", "--cached", "--unified=0")
    return parse_name_status(names), diff


def in_range(repo: Path, base: str) -> tuple[list[ChangedFile], str]:
    spec = f"{base}...HEAD"
    names = _git(repo, "diff", "--name-status", "-M", spec)
    diff = _git(repo, "diff", "--unified=0", spec)
    return parse_name_status(names), diff


def per_commit(repo: Path, base: str) -> list[tuple[str, list[ChangedFile], str]]:
    """Each commit of ``base..HEAD`` against its own parent, oldest first.

    The net diff of a range hides what happened in between: a test weakened in one commit and
    restored in the next, or a secret added and removed. Looking at commits one by one does not.
    """
    shas = _git(repo, "rev-list", "--reverse", f"{base}..HEAD").split()
    out: list[tuple[str, list[ChangedFile], str]] = []
    for sha in shas:
        names = _git(repo, "diff", "--name-status", "-M", f"{sha}^", sha)
        diff = _git(repo, "diff", "--unified=0", f"{sha}^", sha)
        out.append((sha, parse_name_status(names), diff))
    return out


def _check(files: list[ChangedFile], diff: str, branch: str, policy: Policy) -> list[Finding]:
    return [
        *check_protected_paths(files, policy),
        *check_test_edits(files, branch, policy),
        *scan_diff(diff, policy),
    ]


def run_checks(
    repo: Path, policy: Policy, mode: str, base: str = "origin/main", branch: str | None = None
) -> list[Finding]:
    """Run all three checks. ``mode`` is ``staged``, ``range`` (net diff) or ``commits``."""
    if mode == "commits":
        name = branch if branch is not None else current_branch(repo)
        found: list[Finding] = []
        for sha, files, diff in per_commit(repo, base):
            for f in _check(files, diff, name, policy):
                found.append(replace(f, message=f"{f.message} [commit {sha[:7]}]"))
        return found
    if mode == "staged":
        files, diff = staged(repo)
    elif mode == "range":
        files, diff = in_range(repo, base)
    else:
        raise ValueError(f"unknown mode: {mode!r}")
    name = branch if branch is not None else current_branch(repo)
    return _check(files, diff, name, policy)


def render_precommit_script(policy_path: str = "sdlc-policy.json", python: str = "python") -> str:
    """Text of a ``.git/hooks/pre-commit`` that delegates to this kit."""
    return (
        "#!/bin/sh\n"
        "# generated by sdlc_kit: deterministic backstop, works with any agent\n"
        f'exec "{python}" -m sdlc_kit hook --mode staged --policy "{policy_path}"\n'
    )


def install_precommit(
    repo: Path, policy_path: str = "sdlc-policy.json", python: str = "python"
) -> Path:
    hooks = Path(_git(repo, "rev-parse", "--git-path", "hooks").strip())
    if not hooks.is_absolute():
        hooks = repo / hooks
    hooks.mkdir(parents=True, exist_ok=True)
    target = hooks / "pre-commit"
    target.write_text(render_precommit_script(policy_path, python), encoding="utf-8")
    target.chmod(0o755)
    return target
