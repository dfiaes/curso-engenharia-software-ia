"""Ingestão: coleta com filtro e relatório de descarte (lote M07).

Etapa 1 do pipeline: o filtro importa mais do que parece — cada arquivo
descartado é embedding não pago e ruído não indexado. Arquivo gerado,
binário ou fora das extensões conhecidas nem chega ao chunker.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

EXTENSOES = frozenset({".py", ".md", ".json", ".yml", ".yaml", ".toml", ".sql"})
MARCADORES_GERADO = ("ARQUIVO GERADO", "generated by", "@generated")
MAX_BYTES = 512 * 1024


@dataclass(slots=True)
class RelatorioColeta:
    encontrados: int = 0
    descartados: list[str] = field(default_factory=list)

    @property
    def aproveitados(self) -> int:
        return self.encontrados - len(self.descartados)


def coletar(raiz: Path) -> tuple[list[Path], RelatorioColeta]:
    """Percorre a raiz aplicando o filtro; devolve arquivos + relatório."""
    relatorio = RelatorioColeta()
    aceitos: list[Path] = []
    for caminho in sorted(raiz.rglob("*")):
        if not caminho.is_file() or ".venv" in caminho.parts or "__pycache__" in caminho.parts:
            continue
        relatorio.encontrados += 1
        motivo = _motivo_descarte(caminho)
        if motivo is None:
            aceitos.append(caminho)
        else:
            relatorio.descartados.append(f"{caminho.name} ({motivo})")
    return aceitos, relatorio


def _motivo_descarte(caminho: Path) -> str | None:
    if caminho.suffix not in EXTENSOES:
        return "extensão fora do escopo"
    try:
        if caminho.stat().st_size > MAX_BYTES:
            return "grande demais (provável dado)"
        cabeca = caminho.read_text(encoding="utf-8", errors="replace")[:2000]
    except OSError:
        return "ilegível"
    if any(m in cabeca for m in MARCADORES_GERADO):
        return "gerado"
    return None
